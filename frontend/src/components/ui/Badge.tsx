import React from 'react';
import {
  AlertOctagon,
  AlertTriangle,
  Info,
  Shield,
  Zap,
  CheckCircle2,
  HelpCircle,
  FileCode,
  Sparkles,
  Terminal,
} from 'lucide-react';
import type { Category, FindingSource, Severity, VerificationStatus } from '../../types/review';

interface SeverityBadgeProps {
  severity: Severity;
  className?: string;
}

export const SeverityBadge: React.FC<SeverityBadgeProps> = ({ severity, className = '' }) => {
  const styles: Record<Severity, { bg: string; text: string; border: string; icon: React.ReactNode }> = {
    critical: {
      bg: 'bg-red-500/10',
      text: 'text-red-400',
      border: 'border-red-500/30',
      icon: <AlertOctagon className="w-3.5 h-3.5 text-red-400" aria-hidden="true" />,
    },
    high: {
      bg: 'bg-orange-500/10',
      text: 'text-orange-400',
      border: 'border-orange-500/30',
      icon: <AlertTriangle className="w-3.5 h-3.5 text-orange-400" aria-hidden="true" />,
    },
    medium: {
      bg: 'bg-amber-500/10',
      text: 'text-amber-400',
      border: 'border-amber-500/30',
      icon: <AlertTriangle className="w-3.5 h-3.5 text-amber-400" aria-hidden="true" />,
    },
    low: {
      bg: 'bg-blue-500/10',
      text: 'text-blue-400',
      border: 'border-blue-500/30',
      icon: <Info className="w-3.5 h-3.5 text-blue-400" aria-hidden="true" />,
    },
    info: {
      bg: 'bg-slate-500/10',
      text: 'text-slate-400',
      border: 'border-slate-500/30',
      icon: <Info className="w-3.5 h-3.5 text-slate-400" aria-hidden="true" />,
    },
  };

  const style = styles[severity] || styles.info;

  return (
    <span
      className={`inline-flex items-center gap-1.5 px-2 py-0.5 rounded text-xs font-medium border uppercase tracking-wider ${style.bg} ${style.text} ${style.border} ${className}`}
      role="status"
      aria-label={`Severity: ${severity}`}
    >
      {style.icon}
      {severity}
    </span>
  );
};

interface CategoryBadgeProps {
  category: Category;
  className?: string;
}

export const CategoryBadge: React.FC<CategoryBadgeProps> = ({ category, className = '' }) => {
  const getIcon = () => {
    switch (category) {
      case 'security':
        return <Shield className="w-3 h-3 text-red-400" aria-hidden="true" />;
      case 'performance':
        return <Zap className="w-3 h-3 text-amber-400" aria-hidden="true" />;
      case 'correctness':
        return <CheckCircle2 className="w-3 h-3 text-indigo-400" aria-hidden="true" />;
      case 'style':
      case 'maintainability':
      case 'documentation':
      default:
        return <FileCode className="w-3 h-3 text-slate-400" aria-hidden="true" />;
    }
  };

  return (
    <span
      className={`inline-flex items-center gap-1 px-2 py-0.5 rounded text-xs font-mono text-slate-300 bg-slate-800/80 border border-slate-700/60 capitalize ${className}`}
    >
      {getIcon()}
      {category}
    </span>
  );
};

interface SourceBadgeProps {
  source: FindingSource;
  ruleId?: string | null;
  className?: string;
}

export const SourceBadge: React.FC<SourceBadgeProps> = ({ source, ruleId, className = '' }) => {
  const isLlm = source === 'llm';
  return (
    <span
      className={`inline-flex items-center gap-1 px-2 py-0.5 rounded text-xs font-mono ${
        isLlm
          ? 'bg-indigo-950/60 text-indigo-300 border border-indigo-700/50'
          : 'bg-emerald-950/60 text-emerald-300 border border-emerald-700/50'
      } ${className}`}
      title={isLlm ? 'Generated by LLM' : `Deterministic static analysis rule: ${ruleId || source}`}
    >
      {isLlm ? (
        <Sparkles className="w-3 h-3 text-indigo-400" aria-hidden="true" />
      ) : (
        <Terminal className="w-3 h-3 text-emerald-400" aria-hidden="true" />
      )}
      {source.toUpperCase()}
      {ruleId ? `:${ruleId}` : ''}
    </span>
  );
};

interface VerificationBadgeProps {
  status: VerificationStatus;
  className?: string;
}

export const VerificationBadge: React.FC<VerificationBadgeProps> = ({ status, className = '' }) => {
  const isDeterministic = status === 'deterministic';

  return (
    <span
      className={`inline-flex items-center gap-1 px-2 py-0.5 rounded text-xs font-medium border ${
        isDeterministic
          ? 'bg-emerald-500/10 text-emerald-400 border-emerald-500/30'
          : 'bg-amber-500/10 text-amber-300 border-amber-500/30'
      } ${className}`}
      title={
        isDeterministic
          ? 'Verified by deterministic static analysis rule.'
          : 'LLM generated. Line references and patches are unverified and require engineer review.'
      }
    >
      {isDeterministic ? (
        <CheckCircle2 className="w-3 h-3 text-emerald-400" aria-hidden="true" />
      ) : (
        <HelpCircle className="w-3 h-3 text-amber-400" aria-hidden="true" />
      )}
      {isDeterministic ? 'Deterministic' : 'Unverified (LLM)'}
    </span>
  );
};
